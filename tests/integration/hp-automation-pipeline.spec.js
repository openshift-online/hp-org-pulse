    await expect(guide.getByRole('link', { name: 'openshift_backport_pipeline.md', exact: true })).toHaveAttribute('href', /ship-help-bot\/blob\/910ff153b5fad68550cf8868c5f7752fadd3ded2\/.*\/openshift_backport_pipeline\.md$/)
